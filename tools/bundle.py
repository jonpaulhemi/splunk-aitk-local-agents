"""Build the Python libraries bundled in splunk_cloud_connect/lib.

    python tools/bundle.py lock       # resolve requirements/bundle.in -> bundle.lock
    python tools/bundle.py build      # install bundle.lock into splunk_cloud_connect/lib
    python tools/bundle.py inventory  # write docs/bundled-libraries.md from lib/
    python tools/bundle.py package    # dist/splunk_cloud_connect-<version>.tgz

Wheels are always CPython 3.13 manylinux x86_64 (Splunk's Python on our search
heads), whatever machine runs this. `build` installs only hash-pinned wheels.
"""

import argparse
import email.parser
import json
import os
import subprocess
import sys
import tarfile
import tempfile
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
APP = REPO / "splunk_cloud_connect"
LIB = APP / "lib"
REQ_IN = REPO / "requirements" / "bundle.in"
LOCK = REPO / "requirements" / "bundle.lock"
INVENTORY = REPO / "docs" / "bundled-libraries.md"
DIST = REPO / "dist"

TARGET = [
    "--only-binary=:all:",
    "--implementation", "cp",
    "--python-version", "3.13",
    "--abi", "cp313",
    "--platform", "manylinux_2_28_x86_64",
    "--platform", "manylinux_2_17_x86_64",
    "--platform", "manylinux2014_x86_64",
    "--platform", "manylinux_2_5_x86_64",
    "--platform", "manylinux1_x86_64",
]


def _pip(*args):
    subprocess.run([sys.executable, "-m", "pip", *args], check=True)


def lock():
    with tempfile.TemporaryDirectory() as tmp:
        report = Path(tmp) / "report.json"
        _pip("install", "--dry-run", "--quiet", "--ignore-installed", "--target", tmp,
             "--report", str(report), *TARGET, "-r", str(REQ_IN))
        installs = json.loads(report.read_text())["install"]
    lines = ["# Generated by tools/bundle.py lock from bundle.in. Do not edit."]
    for item in sorted(installs, key=lambda i: i["metadata"]["name"].lower()):
        name, version = item["metadata"]["name"], item["metadata"]["version"]
        sha = item["download_info"]["archive_info"]["hashes"]["sha256"]
        lines.append(f"{name}=={version} --hash=sha256:{sha}")
    LOCK.write_text("\n".join(lines) + "\n")
    print(f"{len(installs)} packages pinned in {LOCK.relative_to(REPO)}")


def build():
    if LIB.exists():
        subprocess.run(["rm", "-rf", str(LIB)], check=True)
    _pip("install", "--quiet", "--no-deps", "--require-hashes", "--no-compile",
         "--target", str(LIB), *TARGET, "-r", str(LOCK))
    # Console scripts are useless inside splunkd and point at this machine's Python.
    subprocess.run(["rm", "-rf", str(LIB / "bin")], check=True)
    print(f"built {LIB.relative_to(REPO)}: {_size_mb(LIB):.1f} MB")


def _size_mb(path):
    return sum(p.stat().st_size for p in path.rglob("*") if p.is_file()) / 1e6


def _dists():
    for info in sorted(LIB.glob("*.dist-info"), key=lambda p: p.name.lower()):
        meta = email.parser.Parser().parsestr((info / "METADATA").read_text(errors="replace"))
        records = (info / "RECORD").read_text().splitlines()
        files = [r.split(",", 1)[0] for r in records]
        compiled = any(f.endswith((".so", ".pyd")) or ".so." in f for f in files)
        size = sum((LIB / f).stat().st_size for f in files if (LIB / f).is_file())
        yield meta, compiled, size


def _license(meta):
    expr = meta.get("License-Expression")
    if expr:
        return expr
    classifiers = [c.split(" :: ")[-1] for c in meta.get_all("Classifier") or [] if c.startswith("License ::")]
    if classifiers:
        return "; ".join(classifiers)
    text = (meta.get("License") or "").strip().splitlines()
    return text[0][:60] if text else "UNKNOWN (check the package)"


def inventory():
    rows = list(_dists())
    lines = [
        "# Bundled libraries",
        "",
        "Generated by `python tools/bundle.py inventory` from `splunk_cloud_connect/lib`. Do not edit.",
        "",
        f"{len(rows)} packages, {_size_mb(LIB):.1f} MB unpacked. "
        f"{sum(c for _, c, _ in rows)} contain compiled code (CPython 3.13 manylinux x86_64).",
        "",
        "All licenses are permissive except the MPL-2.0 ones (file-level copyleft: "
        "fine to bundle unmodified; modified files must stay MPL).",
        "",
        "| Package | Version | License | Compiled | Size (MB) |",
        "|---|---|---|---|---|",
    ]
    for meta, compiled, size in rows:
        lines.append(f"| {meta['Name']} | {meta['Version']} | {_license(meta)} | "
                     f"{'yes' if compiled else ''} | {size / 1e6:.1f} |")
    INVENTORY.write_text("\n".join(lines) + "\n")
    print(f"wrote {INVENTORY.relative_to(REPO)}")


def package():
    version = next(line.split("=", 1)[1].strip()
                   for line in (APP / "default" / "app.conf").read_text().splitlines()
                   if line.startswith("version"))
    DIST.mkdir(exist_ok=True)
    out = DIST / f"splunk_cloud_connect-{version}.tgz"

    def keep(info):
        parts = Path(info.name).parts
        if "__pycache__" in parts or (len(parts) > 1 and parts[1] == "local"):
            return None
        info.uid = info.gid = 0
        info.uname = info.gname = ""
        return info

    with tarfile.open(out, "w:gz") as tar:
        tar.add(APP, arcname=APP.name, filter=keep)
    print(f"wrote {out.relative_to(REPO)}: {out.stat().st_size / 1e6:.1f} MB")


if __name__ == "__main__":
    commands = {"lock": lock, "build": build, "inventory": inventory, "package": package}
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("command", choices=commands)
    commands[parser.parse_args().command]()
